async function runFixture(fn) {
  const started = performance.now();
  try {
    const result = await fn();
    return { ...result, error: null, duration_ms: round(performance.now() - started) };
  } catch (error) {
    return {
      id: fn.name || 'unknown',
      title: fn.name || 'unknown',
      gate: true,
      pass: false,
      detail: `threw: ${error instanceof Error ? error.message : String(error)}`,
      measures: {},
      error: error instanceof Error ? error.message : String(error),
      duration_ms: round(performance.now() - started),
    };
  }
}

function buildReport(results) {
  const gatedFailures = results.filter(r => r.gate && !r.pass);
  const passCount = results.filter(r => r.pass).length;
  return {
    schema: 'adaptive-kernel.deterministic-harness/v1',
    generated_at: new Date().toISOString(),
    environment: environmentMetadata(),
    subject: {
      package: '@truefoundry/trueforge-core',
      classes_under_test: [
        'ToolExecutionCoordinator',
        'VerificationCoordinator',
        'ProgressAndRecoveryController',
        'NoProgressController',
        'ToolCapabilityRegistry',
        'validateAgainstInputSchema',
      ],
      policy_version: POLICY_VERSION,
    },
    latency_gate_ms: 100,
    summary: {
      total: results.length,
      passed: passCount,
      failed: results.length - passCount,
      gated_failures: gatedFailures.length,
      ok: gatedFailures.length === 0,
    },
    fixtures: results.map(r => ({
      id: r.id,
      title: r.title,
      gate: r.gate,
      pass: r.pass,
      detail: r.detail ?? '',
      duration_ms: r.duration_ms,
      error: r.error ?? null,
      measures: r.measures,
    })),
    unverified: [externalModelBenchmark],
  };
}

function renderTable(fixtureRows) {
  const rows = fixtureRows.map(r => ({
    status: r.pass ? 'PASS' : 'FAIL',
    id: r.id,
    detail: r.detail ?? '',
  }));
  const idWidth = Math.max(2, ...rows.map(r => r.id.length));
  const lines = [''];
  lines.push('  RESULT  ' + 'ID'.padEnd(idWidth) + '  DETAIL');
  lines.push('  ' + '-'.repeat(6) + '  ' + '-'.repeat(idWidth) + '  ' + '-'.repeat(40));
  for (const row of rows) {
    lines.push(`  ${row.status.padEnd(6)}  ${row.id.padEnd(idWidth)}  ${row.detail}`);
  }
  lines.push('');
  return lines.join('\n');
}

// Run every fixture and return the machine-readable report (no stdout I/O).
// Exposed for the smoke test so it can assert the schema without spawning.
async function runHarness() {
  const results = [];
  for (const fn of fixtures) {
    results.push(await runFixture(fn));
  }
  return buildReport(results);
}

async function main() {
  const report = await runHarness();

  process.stdout.write('===ADAPTIVE_KERNEL_HARNESS_JSON_BEGIN===\n');
  process.stdout.write(JSON.stringify(report, null, 2) + '\n');
  process.stdout.write('===ADAPTIVE_KERNEL_HARNESS_JSON_END===\n');

  const table =
    renderTable(report.fixtures) +
    `  ${report.summary.passed}/${report.summary.total} passed; ` +
    `${report.summary.gated_failures} gated failure(s); ` +
    `external model benchmark: ${externalModelBenchmark.status}\n\n`;
  process.stdout.write(table);

  process.exitCode = report.summary.ok ? 0 : 1;
}

