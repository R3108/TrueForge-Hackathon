/**
 * Deterministic, no-network harness-quality evaluation for the adaptive kernel.
 *
 * This is not a prose report. It exercises the *real* built runtime classes and
 * pure functions exported from the compiled core barrel
 * (`packages/trueforge-core/dist/core/index.mjs`) against paired fixtures,
 * measures them, and emits:
 *
 *   1. one machine-readable JSON object on a marked block, and
 *   2. a compact human table.
 *
 * The classes under test are the genuine kernel coordinator surface:
 *   - `ToolExecutionCoordinator` (prepare/execute/executeBatch/reconcile),
 *   - `VerificationCoordinator` (typed evidence vs prose),
 *   - `ProgressAndRecoveryController` (retry policy + persisted restart
 *     classification from real lifecycle events),
 *   - `NoProgressController` (adaptive stop loop),
 *   - `ToolCapabilityRegistry` / `bindToolCapability`,
 *   - `validateAgainstInputSchema`.
 *
 * Tool sets are plain-JS mock `IToolSet` objects — no MCP transport, no network,
 * no LLM. Every mock records whether `callTool` was dispatched so "blocked
 * before dispatch" and "no dispatch on denial" are asserted against the real
 * coordinator, not a stub. Mock tool latency is deliberately excluded from the
 * coordinator latency measurement: the coordinator distribution is measured only
 * on the pure prepare + non-dispatching execute path (terminal invocations that
 * never reach `callTool`), so no artificial tool sleep contaminates the p95.
 *
 * The harness imports the *built dist* (`.mjs`). The root
 * `benchmark:deterministic` script builds core first, so the sources are proven
 * to typecheck and compile before they are exercised here. No dependencies are
 * required and nothing is generated by hand.
 *
 * External model benchmarking (end-to-end LLM repair quality) is out of scope
 * for a deterministic offline harness and is reported as
 * `unavailable_unverified` rather than fabricated.
 */

