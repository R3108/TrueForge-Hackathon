/*
 * Fixture 7 — ambiguous remote write never retries and classifies
 * reconciliation_required from real lifecycle + recovery.
 *
 * A remote_write whose dispatch throws produces an `unknown` outcome (completion
 * ambiguous). The real ProgressAndRecoveryController.shouldRetry returns false
 * for a non-read/non-safe write, so `execute` never re-dispatches (exactly one
 * dispatch observed). The captured lifecycle events are then fed to the real
 * `classifyPersisted`, which returns `reconciliation_required`. Coordinator
 * `reconcile()` on the unknown outcome also refuses automatic retry.
 */
register(async function ambiguousWriteReconciliation() {
  const writeCap = capability({
    tool_name: 'merge_pull_request',
    side_effect_class: 'remote_write',
    retry_capability: 'reconcile_before_retry',
  });
  const { toolSet, state } = makeMockToolSet({
    tools: [
      { name: 'merge_pull_request', capability: writeCap, behavior: { kind: 'throw', message: 'connection reset' } },
    ],
  });
  const coordinator = new ToolExecutionCoordinator();
  const recovery = new ProgressAndRecoveryController();
  const { events, recorder } = recordingRecorder();

  const outcome = await coordinator.executeInvocation({
    invocation: invocation({
      tool_call_id: 'merge-1',
      tool_set: toolSet,
      tool_name: 'merge_pull_request',
      arguments: { owner: 'o', repo: 'r', pull_number: 1 },
    }),
    context: context({ event_recorder: recorder }),
  });

  const wouldRetry = recovery.shouldRetry({ outcome, attempts_started: 1 });
  const decisions = recovery.classifyPersisted(events);
  const decision = decisions.get('merge-1');
  const reconcile = await coordinator.reconcile({ outcome });

  const pass =
    outcome.status === 'unknown' &&
    state.dispatched.length === 1 &&
    wouldRetry === false &&
    decision !== undefined &&
    decision.disposition === 'reconciliation_required' &&
    decision.automatic_retry_allowed === false &&
    reconcile.retry_allowed === false;

  return {
    id: 'ambiguous_write_reconciliation',
    title: 'ambiguous remote write never retries; classified reconciliation_required',
    gate: true,
    pass,
    detail: `status=${outcome.status}; dispatched=${state.dispatched.length}; disposition=${decision?.disposition ?? 'none'}`,
    measures: {
      outcome_status: outcome.status,
      dispatched_count: state.dispatched.length,
      should_retry: wouldRetry,
      persisted_disposition: decision?.disposition ?? null,
      automatic_retry_allowed: decision?.automatic_retry_allowed ?? null,
      reconcile_retry_allowed: reconcile.retry_allowed,
      lifecycle_event_types: events.map(e => e.type),
    },
  };
});

/*
 * Fixture 8 — persisted restart classification from real coordinator lifecycle
 * events. We drive three genuine executions (a durable terminal write, a
 * before-dispatch validation terminal, and an ambiguous unknown write) through
 * the coordinator with a recording recorder, then classify the union of their
 * emitted lifecycle events with the real ProgressAndRecoveryController.
 */
register(async function persistedRestartClassification() {
  const coordinator = new ToolExecutionCoordinator();
  const { events, recorder } = recordingRecorder();

  // (a) A read that succeeds -> durable terminal (must not be replayed).
  const okCap = capability({
    tool_name: 'get_file_contents',
    side_effect_class: 'read_only',
    retry_capability: 'safe',
    concurrency: { kind: 'parallel_safe' },
  });
  const { toolSet: okSet } = makeMockToolSet({
    tools: [{ name: 'get_file_contents', capability: okCap, behavior: { kind: 'ok', text: 'contents' } }],
  });
  await coordinator.executeInvocation({
    invocation: invocation({ tool_call_id: 'ok-call', tool_set: okSet, tool_name: 'get_file_contents', arguments: {} }),
    context: context({ event_recorder: recorder }),
  });

  // (b) A write whose dispatch throws -> unknown -> reconciliation_required.
  const writeCap = capability({
    tool_name: 'push_files',
    side_effect_class: 'remote_write',
    retry_capability: 'reconcile_before_retry',
  });
  const { toolSet: throwSet } = makeMockToolSet({
    tools: [{ name: 'push_files', capability: writeCap, behavior: { kind: 'throw', message: 'timeout' } }],
  });
  await coordinator.executeInvocation({
    invocation: invocation({ tool_call_id: 'throw-call', tool_set: throwSet, tool_name: 'push_files', arguments: {} }),
    context: context({ event_recorder: recorder }),
  });

  const recovery = new ProgressAndRecoveryController();
  const decisions = recovery.classifyPersisted(events);
  const okDecision = decisions.get('ok-call');
  const throwDecision = decisions.get('throw-call');

  const pass =
    events.length > 0 &&
    okDecision?.disposition === 'terminal' &&
    okDecision.automatic_retry_allowed === false &&
    throwDecision?.disposition === 'reconciliation_required' &&
    throwDecision.completion_unknown === true;

  return {
    id: 'persisted_restart_classification',
    title: 'persisted restart classification from real lifecycle events',
    gate: true,
    pass,
    detail: `ok=${okDecision?.disposition ?? 'none'}; throw=${throwDecision?.disposition ?? 'none'} over ${events.length} events`,
    measures: {
      total_events: events.length,
      classifications: [...decisions.entries()].map(([id, d]) => ({
        tool_call_id: id,
        disposition: d.disposition,
        completion_unknown: d.completion_unknown,
        automatic_retry_allowed: d.automatic_retry_allowed,
        attempts_observed: d.attempts_observed,
      })),
    },
  };
});

/*
 * Fixture 9 — real NoProgressController adaptive stop vs an EXECUTED naive loop,
 * with >= 50% dispatch reduction (no modeled constant for either side).
 *
 * Naive baseline: an agent with no no-progress guard re-issues the same failing
 * write on every attempt up to a fixed retry budget. We actually EXECUTE that
 * loop through the real coordinator with a throwing mock and count how many
 * times `callTool` was dispatched (the naive attempt count is measured, not
 * assumed).
 *
 * Adaptive: the real NoProgressController observes each identical failing batch.
 * We stop dispatching the moment it returns `level === 'stop'` and count how many
 * attempts were dispatched before the stop latched. The reduction is
 * (naive - adaptive) / naive and must be >= 50%.
 */
register(async function adaptiveStopVsNaive() {
  const NAIVE_BUDGET = 10;
  const writeCap = capability({
    tool_name: 'create_or_update_file',
    side_effect_class: 'remote_write',
    retry_capability: 'reconcile_before_retry',
  });
  const failingArgs = { owner: 'o', repo: 'r', path: 'fixture/x.js', content: 'still broken' };

  // --- Naive baseline: execute the same failing write NAIVE_BUDGET times. ---
  const { toolSet: naiveSet, state: naiveState } = makeMockToolSet({
    tools: [{ name: 'create_or_update_file', capability: writeCap, behavior: { kind: 'throw', message: 'boom' } }],
  });
  const naiveCoordinator = new ToolExecutionCoordinator();
  for (let i = 0; i < NAIVE_BUDGET; i++) {
    await naiveCoordinator.executeInvocation({
      invocation: invocation({
        tool_call_id: `naive-${i}`,
        tool_set: naiveSet,
        tool_name: 'create_or_update_file',
        arguments: failingArgs,
      }),
      context: context({ thread_id: 'naive' }),
    });
  }
  const naiveAttempts = naiveState.dispatched.length;

  // --- Adaptive: real NoProgressController gates each identical failing batch. ---
  const { toolSet: adaptiveSet, state: adaptiveState } = makeMockToolSet({
    tools: [{ name: 'create_or_update_file', capability: writeCap, behavior: { kind: 'throw', message: 'boom' } }],
  });
  const adaptiveCoordinator = new ToolExecutionCoordinator();
  const controller = new NoProgressController();
  const observedCalls = [
    {
      stable_tool_set_id: STABLE_TOOL_SET_ID,
      original_tool_name: 'create_or_update_file',
      argument_fingerprint: 'fp-identical',
      normalized_result: 'boom',
      failed: true,
    },
  ];

  let adaptiveAttempts = 0;
  let stoppedAtAttempt = null;
  let stopLevel = null;
  for (let i = 0; i < NAIVE_BUDGET; i++) {
    // Dispatch one attempt (the real failing write), then observe the batch.
    await adaptiveCoordinator.executeInvocation({
      invocation: invocation({
        tool_call_id: `adaptive-${i}`,
        tool_set: adaptiveSet,
        tool_name: 'create_or_update_file',
        arguments: failingArgs,
      }),
      context: context({ thread_id: 'adaptive' }),
    });
    adaptiveAttempts += 1;
    const observation = controller.observe(observedCalls);
    if (observation.level === 'stop') {
      stopLevel = observation.level;
      stoppedAtAttempt = i + 1;
      break;
    }
  }

  const dispatchedAdaptive = adaptiveState.dispatched.length;
  const reductionRatio = naiveAttempts > 0 ? (naiveAttempts - adaptiveAttempts) / naiveAttempts : 0;
  const pass =
    naiveAttempts === NAIVE_BUDGET &&
    stopLevel === 'stop' &&
    dispatchedAdaptive === adaptiveAttempts &&
    reductionRatio >= 0.5;

  return {
    id: 'adaptive_stop_vs_naive',
    title: 'NoProgressController adaptive stop vs executed naive loop (>= 50% fewer dispatches)',
    gate: true,
    pass,
    detail: `naive ${naiveAttempts} vs adaptive ${adaptiveAttempts} dispatched (${round(reductionRatio * 100, 1)}% reduction)`,
    measures: {
      naive_executed_attempts: naiveAttempts,
      adaptive_executed_attempts: adaptiveAttempts,
      adaptive_dispatched_calls: dispatchedAdaptive,
      stopped_at_attempt: stoppedAtAttempt,
      stop_level: stopLevel,
      reduction_ratio: round(reductionRatio, 4),
      reduction_gate: 0.5,
      naive_is_measured_not_modeled: true,
    },
  };
});

