function definition(input) {
  return {
    tool_name: input.tool_name,
    side_effect_class: input.side_effect_class,
    retry_capability: input.retry_capability,
    concurrency: input.concurrency ?? { kind: 'exclusive' },
    timeout_ms: input.timeout_ms ?? null,
    output_schema: input.output_schema ?? null,
    result_size_class: input.result_size_class ?? 'small',
    evidence_capabilities: input.evidence_capabilities ?? [],
    sensitive_argument_paths: input.sensitive_argument_paths ?? [],
    tags: input.tags ?? [],
  };
}

function capability(input) {
  return bindToolCapability({
    stable_tool_set_id: STABLE_TOOL_SET_ID,
    definition: definition(input),
  });
}

/* ------------------------------------------------------------------ *
 * Plain-JS mock IToolSet. Records dispatches; no network, no MCP.     *
 *                                                                     *
 * `callTool` is driven by a per-tool behavior map:                    *
 *   { kind: 'ok', text, structured } -> resolved success              *
 *   { kind: 'error', text }          -> resolved isError result       *
 *   { kind: 'throw', message }       -> dispatch throws (transport)   *
 *   { kind: 'delay', ms, then }      -> awaits ms then applies `then`  *
 * `prepareToolCall` (when provided) can force a required_action        *
 * (approval) with no dispatch, exercising the denial-no-dispatch path. *
 * ------------------------------------------------------------------ */

function toolResult(text, isError, structured) {
  const result = { content: [{ type: 'text', text }] };
  if (isError) {
    result.isError = true;
  }
  if (structured !== undefined) {
    result.structuredContent = structured;
  }
  return { result, wasInitialized: undefined };
}

function makeMockToolSet(options) {
  const capabilities = new Map();
  const inputSchemas = new Map();
  const behaviors = new Map();
  for (const tool of options.tools) {
    capabilities.set(tool.name, tool.capability);
    if (tool.inputSchema !== undefined) {
      inputSchemas.set(tool.name, tool.inputSchema);
    }
    behaviors.set(tool.name, tool.behavior ?? { kind: 'ok', text: `${tool.name}:ok` });
  }

  const state = {
    dispatched: [],
    activeConcurrent: 0,
    maxConcurrent: 0,
  };

  async function applyBehavior(name, behavior) {
    if (behavior.kind === 'throw') {
      throw new Error(behavior.message ?? `mock ${name} dispatch failed`);
    }
    if (behavior.kind === 'delay') {
      await new Promise(resolve => globalThis.setTimeout(resolve, behavior.ms));
      return applyBehavior(name, behavior.then);
    }
    if (behavior.kind === 'error') {
      return toolResult(behavior.text ?? `${name}:error`, true);
    }
    return toolResult(behavior.text ?? `${name}:ok`, false, behavior.structured);
  }

  const toolSet = {
    name: options.name ?? STABLE_TOOL_SET_ID,
    id: options.id ?? STABLE_TOOL_SET_ID,
    preload: true,
    hasPreloadedTools: true,
    listTools() {
      return Promise.resolve({ result: { tools: [] }, wasInitialized: undefined });
    },
    getToolCapability(toolName) {
      return capabilities.get(toolName);
    },
    getToolInputSchema(toolName) {
      return inputSchemas.get(toolName);
    },
    toolCallInfo(params) {
      return Promise.resolve({
        type: 'mcp',
        mcp_server_id: toolSet.id,
        mcp_server_name: toolSet.name,
        original_tool_name: params.name,
        is_approval_required: false,
      });
    },
    async callTool(params) {
      state.dispatched.push(params.name);
      state.activeConcurrent += 1;
      state.maxConcurrent = Math.max(state.maxConcurrent, state.activeConcurrent);
      try {
        return await applyBehavior(params.name, behaviors.get(params.name) ?? { kind: 'ok' });
      } finally {
        state.activeConcurrent -= 1;
      }
    },
  };

  if (options.requiredAction) {
    // A preflight that resolves to a required action (approval) and never dispatches.
    toolSet.prepareToolCall = () =>
      Promise.resolve({
        kind: 'required_action',
        response: { approvalRequired: { tool_info: { type: 'mcp', original_tool_name: 'x' } } },
      });
  }

  return { toolSet, state };
}

/* ------------------------------------------------------------------ *
 * Response text extraction (isCallToolResponseResult is internal).    *
 * ------------------------------------------------------------------ */

function responseText(response) {
  const content = response?.result?.content;
  if (!Array.isArray(content)) {
    return '';
  }
  const first = content[0];
  return first && first.type === 'text' ? first.text : '';
}

function errorCodeOf(response) {
  const text = responseText(response);
  try {
    const parsed = JSON.parse(text);
    return typeof parsed?.error === 'string' ? parsed.error : null;
  } catch {
    return null;
  }
}

/* ------------------------------------------------------------------ *
 * A recording event recorder that captures real lifecycle events so   *
 * ProgressAndRecoveryController.classifyPersisted runs on genuine      *
 * coordinator output rather than hand-authored events.                *
 * ------------------------------------------------------------------ */

function recordingRecorder() {
  const events = [];
  return {
    events,
    recorder: event => {
      events.push(event);
      return Promise.resolve();
    },
  };
}

function invocation(input) {
  return {
    tool_call_id: input.tool_call_id,
    tool_set: input.tool_set,
    tool_name: input.tool_name,
    arguments: input.arguments,
    approval_decision: input.approval_decision,
  };
}

/* ------------------------------------------------------------------ *
 * Statistics helpers.                                                 *
 * ------------------------------------------------------------------ */

function percentile(sortedAsc, p) {
  if (sortedAsc.length === 0) {
    return Number.POSITIVE_INFINITY;
  }
  const index = Math.ceil(sortedAsc.length * p) - 1;
  const clamped = Math.min(Math.max(index, 0), sortedAsc.length - 1);
  return sortedAsc[clamped];
}

function round(value, digits = 4) {
  if (!Number.isFinite(value)) {
    return value;
  }
  const factor = 10 ** digits;
  return Math.round(value * factor) / factor;
}

function distribution(samplesMs) {
  const sorted = [...samplesMs].sort((a, b) => a - b);
  const sum = sorted.reduce((acc, value) => acc + value, 0);
  return {
    samples: sorted.length,
    min_ms: round(sorted[0] ?? 0),
    p50_ms: round(percentile(sorted, 0.5)),
    p95_ms: round(percentile(sorted, 0.95)),
    p99_ms: round(percentile(sorted, 0.99)),
    max_ms: round(sorted[sorted.length - 1] ?? 0),
    mean_ms: round(sorted.length ? sum / sorted.length : 0),
  };
}

